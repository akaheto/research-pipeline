import { NextRequest, NextResponse } from "next/server";

function generateMarkdown(result: any): string {
  let md = `# Research Report: ${result.topic}\n\n`;
  md += `**Generated:** ${new Date().toLocaleString()}\n`;
  md += `**Findings:** ${result.findings.length}\n\n`;

  if (result.summary) {
    md += `## Summary\n\n${result.summary}\n\n`;
  }

  md += `## Key Findings\n\n`;
  result.findings.forEach((finding: any, i: number) => {
    md += `### ${i + 1}. ${finding.text.substring(0, 80)}...\n\n`;
    md += `- **Source:** [${finding.source.title}](${finding.source.url})\n`;
    md += `- **Domain:** ${finding.source.domain}\n`;
    md += `- **Relevance:** ${(finding.scores.relevance * 100).toFixed(0)}%\n`;
    md += `- **Credibility:** ${(finding.scores.credibility * 100).toFixed(0)}%\n`;
    md += `- **Recency:** ${(finding.scores.recency * 100).toFixed(0)}%\n`;
    md += `- **Combined Score:** ${(finding.scores.combined * 100).toFixed(0)}%\n\n`;
  });

  if (result.knowledge_base_insights.length > 0) {
    md += `## Related Knowledge Base Insights\n\n`;
    result.knowledge_base_insights.forEach((insight: string) => {
      md += `- ${insight}\n`;
    });
    md += `\n`;
  }

  md += `## All Sources\n\n`;
  result.findings.forEach((finding: any, i: number) => {
    md += `${i + 1}. [${finding.source.title}](${finding.source.url})\n`;
    md += `   - Retrieved: ${new Date(finding.source.retrieved_at).toLocaleString()}\n\n`;
  });

  md += `---\n*Generated by Research Pipeline*`;
  return md;
}

function generateWord(result: any): string {
  // For Word format, we'll return a simplified text representation
  // In production, use python-docx via API call
  let text = `RESEARCH REPORT: ${result.topic}\n\n`;
  text += `Generated: ${new Date().toLocaleString()}\n`;
  text += `Findings: ${result.findings.length}\n\n`;

  if (result.summary) {
    text += `SUMMARY\n${result.summary}\n\n`;
  }

  text += `KEY FINDINGS\n`;
  result.findings.forEach((finding: any, i: number) => {
    text += `\n${i + 1}. ${finding.text}\n`;
    text += `Source: ${finding.source.title} (${finding.source.domain})\n`;
    text += `URL: ${finding.source.url}\n`;
    text += `Scores: Relevance ${(finding.scores.relevance * 100).toFixed(0)}% | `;
    text += `Credibility ${(finding.scores.credibility * 100).toFixed(0)}% | `;
    text += `Recency ${(finding.scores.recency * 100).toFixed(0)}% | `;
    text += `Combined ${(finding.scores.combined * 100).toFixed(0)}%\n`;
  });

  if (result.knowledge_base_insights.length > 0) {
    text += `\nKNOWLEDGE BASE INSIGHTS\n`;
    result.knowledge_base_insights.forEach((insight: string) => {
      text += `• ${insight}\n`;
    });
  }

  text += `\nSOURCES\n`;
  result.findings.forEach((finding: any, i: number) => {
    text += `${i + 1}. ${finding.source.title}\n   URL: ${finding.source.url}\n`;
  });

  return text;
}

export async function POST(request: NextRequest) {
  try {
    const body = await request.json();
    const { result, format } = body;

    if (!result || !format) {
      return NextResponse.json(
        { error: "Result and format are required" },
        { status: 400 }
      );
    }

    let content: string;
    let contentType: string;
    let filename: string;

    if (format === "markdown") {
      content = generateMarkdown(result);
      contentType = "text/markdown; charset=utf-8";
      filename = `${result.topic.replace(/\s+/g, "_")}.md`;
    } else if (format === "docx") {
      // For DOCX, return as .docx text representation
      // In production, generate actual .docx binary via Python API
      content = generateWord(result);
      contentType = "application/vnd.openxmlformats-officedocument.wordprocessingml.document";
      filename = `${result.topic.replace(/\s+/g, "_")}.docx`;
    } else {
      return NextResponse.json({ error: "Invalid format" }, { status: 400 });
    }

    return new NextResponse(content, {
      headers: {
        "Content-Type": contentType,
        "Content-Disposition": `attachment; filename="${filename}"`,
      },
    });
  } catch (error) {
    console.error("Export error:", error);
    return NextResponse.json({ error: "Export failed" }, { status: 500 });
  }
}
